/**
 * 区域 5「熔岩神殿」怪物运行时素材构建器。
 *
 * 源图不进入主仓。每个 stable key 在外置美术源仓中保留：
 *   monsters/<id>-chroma.png
 *   monsters/<id>-alpha.png
 *
 * 本脚本会把官方抠图工具产出的 alpha 母版统一为 512×512 透明 WebP，
 * 并将源仓 chroma 文件重建为严格 #00ff00 背景。ImageGen 原始输出仍永久
 * 保留在 ~/.codex/generated_images，不会被移动或覆盖。
 */

import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { REGION5_MONSTERS } from './region5-assets-manifest.mjs';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(SCRIPT_DIR, '..');
const DEFAULT_SOURCE_ROOT =
  'C:/Users/Administrator/Desktop/二次元传奇项目/yingrenchuanshuo-art-source-r5/monsters';
const SOURCE_ROOT = resolve(process.env.R5_MONSTER_SOURCE ?? DEFAULT_SOURCE_ROOT);
const OUTPUT_ROOT = resolve(ROOT, 'public/assets/monsters/r5');
const LOCK_PATH = resolve(ROOT, 'art-source/regions/r5/MONSTERS-SHA256.txt');

const CANVAS_SIZE = 512;
const CONTENT_LIMIT = 480;
const LAST_VISIBLE_Y = 503;
const ALPHA_THRESHOLD = 8;
const MAX_BYTES = 120 * 1024;
const MIN_QUALITY = 72;

function sha256(buffer) {
  return createHash('sha256').update(buffer).digest('hex');
}

function findAlphaBounds(data, width, height, threshold = ALPHA_THRESHOLD) {
  let left = width;
  let top = height;
  let right = -1;
  let bottom = -1;

  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      if (data[(y * width + x) * 4 + 3] <= threshold) continue;
      left = Math.min(left, x);
      top = Math.min(top, y);
      right = Math.max(right, x);
      bottom = Math.max(bottom, y);
    }
  }

  if (right < left || bottom < top) {
    throw new Error('alpha 母版没有可见像素');
  }
  return {
    left,
    top,
    width: right - left + 1,
    height: bottom - top + 1,
  };
}

async function normalizeChroma(alphaPath, chromaPath) {
  const alphaMetadata = await sharp(alphaPath).metadata();
  if (!alphaMetadata.width || !alphaMetadata.height) {
    throw new Error(`${alphaPath} 无法读取尺寸`);
  }

  await sharp({
    create: {
      width: alphaMetadata.width,
      height: alphaMetadata.height,
      channels: 3,
      background: { r: 0, g: 255, b: 0 },
    },
  })
    .composite([{ input: alphaPath }])
    .png({ compressionLevel: 9, adaptiveFiltering: true })
    .toFile(chromaPath);
}

async function makeRuntimeCanvas(alphaPath) {
  const resized = await sharp(alphaPath)
    .ensureAlpha()
    .trim({
      background: { r: 0, g: 0, b: 0, alpha: 0 },
      threshold: ALPHA_THRESHOLD,
    })
    .resize({
      width: CONTENT_LIMIT,
      height: CONTENT_LIMIT,
      fit: 'inside',
      withoutEnlargement: false,
      kernel: sharp.kernel.lanczos3,
    })
    .png()
    .toBuffer();

  const { data, info } = await sharp(resized)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const bounds = findAlphaBounds(data, info.width, info.height);
  const tight = await sharp(resized).extract(bounds).png().toBuffer();
  const left = Math.floor((CANVAS_SIZE - bounds.width) / 2);
  const top = LAST_VISIBLE_Y - bounds.height + 1;

  if (left < 0 || top < 0) {
    throw new Error(`${alphaPath} 的主体超过 ${CONTENT_LIMIT}×${CONTENT_LIMIT}`);
  }

  return sharp({
    create: {
      width: CANVAS_SIZE,
      height: CANVAS_SIZE,
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite([{ input: tight, left, top }])
    .png()
    .toBuffer();
}

async function encodeWithinBudget(canvas, outputPath) {
  for (let quality = 88; quality >= MIN_QUALITY; quality -= 2) {
    const output = await sharp(canvas)
      .webp({
        quality,
        alphaQuality: 100,
        effort: 6,
        smartSubsample: true,
        preset: 'picture',
      })
      .toBuffer();
    if (output.byteLength <= MAX_BYTES) {
      await writeFile(outputPath, output);
      return { bytes: output.byteLength, quality };
    }
  }

  throw new Error(`${outputPath} 在 WebP quality ${MIN_QUALITY} 时仍超过 ${MAX_BYTES} bytes`);
}

await mkdir(OUTPUT_ROOT, { recursive: true });
await mkdir(dirname(LOCK_PATH), { recursive: true });

const lockLines = [
  '# R5 monster source SHA256',
  '# Generated by scripts/build-region5-monsters.mjs',
];

for (const monster of REGION5_MONSTERS) {
  const chromaPath = resolve(SOURCE_ROOT, `${monster.id}-chroma.png`);
  const alphaPath = resolve(SOURCE_ROOT, `${monster.id}-alpha.png`);
  const outputPath = resolve(OUTPUT_ROOT, `${monster.id}.webp`);

  // ImageGen 的绿幕会有极轻微压缩/采样偏色。以官方抠图后的 alpha 母版
  // 重建严格纯绿源图，同时不触碰 generated_images 中的原始调用结果。
  await normalizeChroma(alphaPath, chromaPath);
  const canvas = await makeRuntimeCanvas(alphaPath);
  const encoded = await encodeWithinBudget(canvas, outputPath);

  const chroma = await readFile(chromaPath);
  const alpha = await readFile(alphaPath);
  lockLines.push(`${sha256(chroma)}  monsters/${monster.id}-chroma.png`);
  lockLines.push(`${sha256(alpha)}  monsters/${monster.id}-alpha.png`);
  console.log(`✓ ${monster.id}.webp ${Math.round(encoded.bytes / 1024)} KiB q${encoded.quality}`);
}

await writeFile(LOCK_PATH, `${lockLines.join('\n')}\n`, 'utf8');
console.log(`✓ 源图 SHA256 锁：${LOCK_PATH}`);
