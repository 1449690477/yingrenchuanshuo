const SEEDS: Readonly<Record<ClassId, TierSeeds>> = {
  swordsman: SWORDSMAN_INTERLUDES,
  witch: WITCH_INTERLUDES,
  shaman: SHAMAN_INTERLUDES,
  catkin: CATKIN_INTERLUDES,
};

const TIER_IDS = AFFECTION_RULES.tiers.map((tier) => tier.id) as AffectionTierId[];

export const AFFECTION_INTERLUDES: readonly AffectionInterludeDefinition[] = CLASS_IDS.flatMap(
  (classId) =>
    TIER_IDS.flatMap((tierId) => {
      const tier = AFFECTION_RULES.tiers.find((entry) => entry.id === tierId);
      if (!tier) throw new Error(`[好感幕间] 未找到阶段 ${tierId}`);
      return SEEDS[classId][tierId].map(
        ([title, narration, spoken, mood], index): AffectionInterludeDefinition => ({
          id: `interlude_${classId}_${tierId}_${String(index + 1).padStart(2, '0')}`,
          classId,
          tierId,
          tierLabel: tier.label,
          minPoints: tier.minPoints,
          title,
          dialogue: [
            { text: narration, mood: 'calm' },
            {
              speaker:
                classId === 'swordsman'
                  ? '剑姬'
                  : classId === 'witch'
                    ? '魔女'
                    : classId === 'shaman'
                      ? '巫女'
                      : '喵喵',
              text: spoken,
              mood,
            },
          ],
        }),
      );
    }),
);

export function affectionInterludesForClass(
  classId: ClassId,
): readonly AffectionInterludeDefinition[] {
  return AFFECTION_INTERLUDES.filter((entry) => entry.classId === classId);
}
